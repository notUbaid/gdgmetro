export type TransitMode = 'metro' | 'brts' | 'amts' | 'walk';

export interface TransitStop {
  id: string;
  name: string;
  nameGu: string;
  nameHi: string;
  mode: 'metro' | 'brts' | 'amts';
  coordinates: [number, number]; // [lat, lng]
  corridor: string;
  isInterchange?: boolean;
  connectedStops?: { stopId: string; walkMeters: number; walkMinutes: number }[];
  operatingHours?: { start: string; end: string };
  headwayMinutes?: number;
}

export interface TransitRoute {
  id: string;
  name: string;
  code: string;
  mode: 'metro' | 'brts' | 'amts';
  color: string;
  textColor?: string;
  stops: string[]; // ordered list of stop IDs
  averageSpeedKmH: number;
  baseFare: number;
}

